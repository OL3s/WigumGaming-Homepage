const fs = require('fs');
const path = require('path');

const projectRoot = path.resolve(__dirname, '..');
const gamesContentDir = path.join(projectRoot, 'src', 'content', 'games');
const outputFile = path.join(projectRoot, 'src', 'generated', 'blogPosts.js');

function parseFrontMatter(fileContent) {
  const match = fileContent.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);

  if (!match) {
    return { data: {}, body: fileContent.trim() };
  }

  const data = match[1].split(/\r?\n/).reduce((result, line) => {
    const separatorIndex = line.indexOf(':');

    if (separatorIndex === -1) {
      return result;
    }

    const key = line.slice(0, separatorIndex).trim();
    const value = line.slice(separatorIndex + 1).trim().replace(/^['"]|['"]$/g, '');

    if (key) {
      result[key] = value;
    }

    return result;
  }, {});

  return {
    data,
    body: fileContent.slice(match[0].length).trim(),
  };
}

function titleFromFileName(fileName) {
  return fileName
    .replace(/^\d{4}-\d{2}-\d{2}-?/, '')
    .replace(/\.md$/i, '')
    .split('-')
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
}

function dateFromFileName(fileName) {
  const match = fileName.match(/^(\d{4}-\d{2}-\d{2})/);
  return match ? match[1] : '';
}

function readBlogPosts() {
  if (!fs.existsSync(gamesContentDir)) {
    return {};
  }

  return fs.readdirSync(gamesContentDir, { withFileTypes: true }).reduce((postsByGame, gameEntry) => {
    if (!gameEntry.isDirectory()) {
      return postsByGame;
    }

    const gameSlug = gameEntry.name;
    const blogDir = path.join(gamesContentDir, gameSlug, 'blog');

    if (!fs.existsSync(blogDir)) {
      return postsByGame;
    }

    const posts = fs.readdirSync(blogDir, { withFileTypes: true })
      .filter((entry) => entry.isFile() && entry.name.toLowerCase().endsWith('.md'))
      .map((entry) => {
        const filePath = path.join(blogDir, entry.name);
        const fileContent = fs.readFileSync(filePath, 'utf8');
        const { data, body } = parseFrontMatter(fileContent);

        return {
          slug: entry.name.replace(/\.md$/i, ''),
          title: data.title || titleFromFileName(entry.name),
          date: data.date || dateFromFileName(entry.name),
          excerpt: data.excerpt || '',
          body,
        };
      })
      .sort((a, b) => {
        const dateComparison = b.date.localeCompare(a.date);
        return dateComparison || b.slug.localeCompare(a.slug);
      });

    postsByGame[gameSlug] = posts;
    return postsByGame;
  }, {});
}

fs.mkdirSync(path.dirname(outputFile), { recursive: true });

const generatedContent = `// This file is generated by scripts/generate-blog-posts.js. Do not edit manually.\nconst blogPostsByGame = ${JSON.stringify(readBlogPosts(), null, 2)};\n\nexport default blogPostsByGame;\n`;

fs.writeFileSync(outputFile, generatedContent);
