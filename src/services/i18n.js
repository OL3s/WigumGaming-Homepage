export const DEFAULT_LANGUAGE = I18N.defaultLanguage;
export const SUPPORTED_LANGUAGES = I18N.languages;

export function normalizeLanguage(language) {
  return SUPPORTED_LANGUAGES.some((entry) => entry.code === language) ? language : DEFAULT_LANGUAGE;
}

export function readInitialLanguage(search = '') {
  const queryLanguage = new URLSearchParams(search).get('lang');

  if (queryLanguage) {
    return normalizeLanguage(queryLanguage);
  }

  try {
    return normalizeLanguage(window.localStorage.getItem(I18N.storageKey));
  } catch (error) {
    return DEFAULT_LANGUAGE;
  }
}

export function writeLanguage(language) {
  try {
    window.localStorage.setItem(I18N.storageKey, normalizeLanguage(language));
  } catch (error) {
    // Storage can be unavailable in private/browser-restricted contexts.
  }
}

export function createTranslator(language) {
  const selectedLanguage = normalizeLanguage(language);
  const selectedTranslations = I18N.strings[selectedLanguage] || I18N.strings[DEFAULT_LANGUAGE];

  return function translate(key) {
    return selectedTranslations[key] || I18N.strings[DEFAULT_LANGUAGE][key] || key;
  };
}
